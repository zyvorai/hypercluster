from __future__ import annotations

import shutil
from pathlib import Path

from hypercluster import log
from hypercluster.models import ClusterConfig


def _node_entry(name: str, ip: str, ssh_port: int = 22) -> str:
    lines = [
        f"    {name}:",
        f"      ansible_host: {ip}",
        f"      ip: {ip}",
        f"      access_ip: {ip}",
    ]
    if ssh_port and ssh_port != 22:
        lines.append(f"      ansible_port: {ssh_port}")
    return "\n".join(lines)


def generate_hosts_yaml(dest_dir: Path, cfg: ClusterConfig) -> None:
    dest_dir.mkdir(parents=True, exist_ok=True)
    hosts_file = dest_dir / "hosts.yaml"
    cp_ips = cfg.control_plane_ips()
    worker_ips = cfg.worker_ips()

    lines = ["all:", "  hosts:"]
    for i, ip in enumerate(cp_ips, 1):
        lines.append(_node_entry(f"master{i}", ip, cfg.SSH_PORT))
    for i, ip in enumerate(worker_ips, 1):
        lines.append(_node_entry(f"worker{i}", ip, cfg.SSH_PORT))

    lines += [
        "  children:",
        "    kube_control_plane:",
        "      hosts:",
    ]
    for i in range(1, len(cp_ips) + 1):
        lines.append(f"        master{i}:")

    lines += ["    kube_node:", "      hosts:"]
    for i in range(1, len(worker_ips) + 1):
        lines.append(f"        worker{i}:")

    lines += ["    etcd:", "      hosts:"]
    for i in range(1, len(cp_ips) + 1):
        lines.append(f"        master{i}:")

    lines += [
        "    k8s_cluster:",
        "      children:",
        "        kube_control_plane:",
        "        kube_node:",
        "    calico_rr:",
        "      hosts: {}",
    ]

    hosts_file.write_text("\n".join(lines) + "\n")
    log.ok(f"hosts.yaml written → {hosts_file}")


def generate_group_vars(dest_dir: Path, cfg: ClusterConfig) -> None:
    cluster_dir = dest_dir / "group_vars" / "k8s_cluster"
    all_dir = dest_dir / "group_vars" / "all"
    cluster_dir.mkdir(parents=True, exist_ok=True)
    all_dir.mkdir(parents=True, exist_ok=True)

    (cluster_dir / "k8s-cluster.yml").write_text(
        f"# Generated by hypercluster — do not edit by hand.\n"
        f"kube_version: {cfg.KUBE_VERSION}\n"
        f"container_manager: {cfg.CONTAINER_MANAGER}\n"
        f"kube_network_plugin: {cfg.CNI_PLUGIN or 'cilium'}\n"
        f"kube_network_plugin_multus: false\n\n"
        f"kube_service_addresses: {cfg.KUBE_SERVICE_ADDRESSES}\n"
        f"kube_pods_subnet: {cfg.KUBE_PODS_SUBNET}\n\n"
        f"kubelet_cgroup_driver: systemd\n"
        f"kubeconfig_localhost: true\n"
    )
    log.ok("k8s-cluster.yml written")

    (cluster_dir / "addons.yml").write_text(
        f"# Generated by hypercluster — do not edit by hand.\n"
        f"metrics_server_enabled: {str(cfg.METRICS_SERVER_ENABLED).lower()}\n"
    )
    log.ok("addons.yml written")

    ssh_key = cfg.resolved_ssh_key()
    (all_dir / "all.yml").write_text(
        f"# Generated by hypercluster — do not edit by hand.\n"
        f"ansible_user: {cfg.SSH_USER}\n"
        f"ansible_ssh_private_key_file: {ssh_key}\n"
        f"ansible_become: true\n"
    )
    log.ok("all.yml written")


def init(kubespray_dir: Path, cfg: ClusterConfig, force: bool = False) -> None:
    inv_dest = kubespray_dir / "inventory" / cfg.CLUSTER_NAME
    sample_dir = kubespray_dir / "inventory" / "sample"

    if not sample_dir.is_dir():
        log.die(f"Kubespray sample inventory not found: {sample_dir} — is the clone complete?")

    if inv_dest.is_dir():
        if not force:
            log.die(
                f"Inventory already exists: {inv_dest}\n"
                "Re-run with -f to overwrite, or delete it manually."
            )
        log.warn(f"Overwriting existing inventory (--force): {inv_dest}")
        shutil.rmtree(inv_dest)

    shutil.copytree(str(sample_dir), str(inv_dest))
    generate_hosts_yaml(inv_dest, cfg)
    generate_group_vars(inv_dest, cfg)
    log.ok(f"Inventory ready at {inv_dest} \U0001f4cb")
