from __future__ import annotations

from pathlib import Path

from hypercluster import log


def _ask(prompt: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    try:
        val = input(f"{prompt}{suffix}: ").strip()
    except (EOFError, KeyboardInterrupt):
        print()
        log.die("Wizard interrupted.")
    return val or default


def write_config(config_path: str) -> None:
    log.section("Cluster configuration wizard")
    print("Answer the questions below to generate cluster.conf.")
    print("Press Enter to accept defaults.\n")

    cluster_name = _ask("Cluster name", "my-cluster")
    distro = _ask("K8s distro [kubespray/k3s/rke2/microk8s]", "k3s")
    ssh_user = _ask("SSH user", "ubuntu")
    ssh_key = _ask("SSH key path", "~/.ssh/id_rsa")
    ssh_port = _ask("SSH port", "22")
    cp_ips = _ask("Control plane IPs (space-separated)", "")
    worker_ips = _ask("Worker IPs (space-separated, leave empty for single-node)", "")
    kubeconfig_output = _ask("Kubeconfig output path", "~/.kube/config")

    distro_section = ""
    if distro == "kubespray":
        kubespray_version = _ask("Kubespray version", "v2.26.0")
        kube_version = _ask("Kubernetes version", "v1.31.0")
        distro_section = (
            f"\nKUBESPRAY_VERSION=\"{kubespray_version}\"\n"
            f"KUBE_VERSION=\"{kube_version}\"\n"
            f"CONTAINER_MANAGER=\"containerd\"\n"
            f"CNI_PLUGIN=\"cilium\"\n"
        )
    elif distro == "k3s":
        k3s_channel = _ask("k3s channel (stable/latest)", "stable")
        metallb_pool = _ask("MetalLB IP pool (e.g. 192.168.1.240-192.168.1.250)", "")
        distro_section = f'\nK3S_CHANNEL="{k3s_channel}"\n'
        if metallb_pool:
            distro_section += f'METALLB_IP_POOL="{metallb_pool}"\n'

    content = (
        f'# Generated by hypercluster wizard\n'
        f'CLUSTER_NAME="{cluster_name}"\n'
        f'K8S_DISTRO="{distro}"\n\n'
        f'# SSH\n'
        f'SSH_USER="{ssh_user}"\n'
        f'SSH_KEY="{ssh_key}"\n'
        f'SSH_PORT="{ssh_port}"\n\n'
        f'# Nodes\n'
        f'CONTROL_PLANE_IPS="{cp_ips}"\n'
        f'WORKER_IPS="{worker_ips}"\n\n'
        f'# kubeconfig\n'
        f'KUBECONFIG_OUTPUT="{kubeconfig_output}"\n'
        f'{distro_section}'
    )

    out = Path(config_path).expanduser()
    if out.is_file():
        log.warn(f"Overwriting existing config: {out}")
    out.write_text(content)
    log.ok(f"Config written → {out}")
    print(f"\nNext steps:")
    print(f"  hypercluster -c {out} preflight")
    print(f"  hypercluster -c {out} deploy")
