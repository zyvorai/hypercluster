#!/usr/bin/env bash
# test-local.sh — Spin up Multipass VMs on macOS and run a hypercluster deployment against them.
#
# Creates 1 control-plane + 2 worker Ubuntu VMs, generates a cluster.conf,
# runs hypercluster deploy, and verifies the cluster is healthy.
#
# Usage:
#   chmod +x scripts/test-local.sh
#   ./scripts/test-local.sh             # full deploy
#   ./scripts/test-local.sh --clean     # destroy VMs and remove test config
#   ./scripts/test-local.sh --vms-only  # create VMs, print IPs, then stop (no deploy)
#
# Prerequisites:  run scripts/setup-macos.sh first.

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=lib/log.sh
source "$REPO_DIR/lib/log.sh"

TEST_CONF="$REPO_DIR/cluster-test.conf"
SSH_KEY="$HOME/.ssh/id_hypercluster_test"

VM_MASTER="hc-master"
VM_WORKERS=("hc-worker1" "hc-worker2")
VM_CPUS=2
VM_MEM="3G"
VM_DISK="15G"
VM_IMAGE="22.04"   # Ubuntu LTS

# ── prerequisites check ───────────────────────────────────────────────────────
check_prereqs() {
  section "Checking prerequisites"
  local missing=0
  for cmd in multipass ansible kubectl; do
    if command -v "$cmd" &>/dev/null; then
      info "$cmd found"
    else
      warn "$cmd not found — run scripts/setup-macos.sh first"
      (( missing++ )) || true
    fi
  done
  [[ "$missing" -eq 0 ]] || die "$missing missing tool(s). Run scripts/setup-macos.sh first."
}

# ── SSH key ───────────────────────────────────────────────────────────────────
ensure_ssh_key() {
  if [[ -f "$SSH_KEY" ]]; then
    info "SSH key already exists: $SSH_KEY"
    return
  fi
  section "Generating test SSH key"
  ssh-keygen -t ed25519 -f "$SSH_KEY" -C "hypercluster-test" -N ""
  chmod 600 "$SSH_KEY"
  info "SSH key created: $SSH_KEY"
}

# ── VM lifecycle ──────────────────────────────────────────────────────────────
vm_exists() {
  multipass list --format csv 2>/dev/null | grep -q "^$1,"
}

vm_ip() {
  multipass info "$1" --format csv 2>/dev/null | awk -F',' 'NR==2{print $3}'
}

create_vm() {
  local name="$1"
  if vm_exists "$name"; then
    info "VM already exists: $name"
    multipass start "$name" 2>/dev/null || true
    return
  fi
  info "Creating VM: $name (${VM_CPUS} CPU, ${VM_MEM} RAM, ${VM_DISK} disk) …"
  multipass launch "$VM_IMAGE" \
    --name "$name" \
    --cpus "$VM_CPUS" \
    --memory "$VM_MEM" \
    --disk "$VM_DISK"
  info "VM created: $name"
}

inject_ssh_key() {
  local name="$1"
  local pubkey
  pubkey=$(cat "${SSH_KEY}.pub")
  info "Injecting SSH key into $name …"
  # Use multipass exec to write the key (avoids chicken-and-egg SSH problem)
  multipass exec "$name" -- bash -c "
    mkdir -p /root/.ssh && chmod 700 /root/.ssh
    echo '$pubkey' >> /root/.ssh/authorized_keys
    chmod 600 /root/.ssh/authorized_keys
    # Allow root SSH (Multipass uses ubuntu user by default — add root access)
    sudo bash -c \"
      cp /home/ubuntu/.ssh/authorized_keys /root/.ssh/authorized_keys 2>/dev/null || true
      echo '$pubkey' >> /root/.ssh/authorized_keys
      sed -i 's/#PermitRootLogin.*/PermitRootLogin yes/' /etc/ssh/sshd_config
      sed -i 's/PermitRootLogin prohibit-password/PermitRootLogin yes/' /etc/ssh/sshd_config
      systemctl restart ssh
    \"
  "
  info "SSH key injected into $name"
}

prepare_vm() {
  local name="$1"
  info "Preparing $name (disable swap, update packages) …"
  multipass exec "$name" -- sudo bash -c "
    swapoff -a
    sed -i '/swap/d' /etc/fstab
    apt-get update -qq
    apt-get install -y -qq python3 curl
  "
}

create_vms() {
  section "Creating Multipass VMs"
  create_vm "$VM_MASTER"
  for w in "${VM_WORKERS[@]}"; do create_vm "$w"; done

  section "Injecting SSH keys"
  inject_ssh_key "$VM_MASTER"
  for w in "${VM_WORKERS[@]}"; do inject_ssh_key "$w"; done

  section "Preparing VMs"
  prepare_vm "$VM_MASTER"
  for w in "${VM_WORKERS[@]}"; do prepare_vm "$w"; done
}

get_ips() {
  MASTER_IP=$(vm_ip "$VM_MASTER")
  WORKER_IPS=()
  for w in "${VM_WORKERS[@]}"; do
    WORKER_IPS+=("$(vm_ip "$w")")
  done

  [[ -n "$MASTER_IP" ]]       || die "Could not get IP for $VM_MASTER"
  [[ -n "${WORKER_IPS[0]}" ]] || die "Could not get IP for ${VM_WORKERS[0]}"
  [[ -n "${WORKER_IPS[1]}" ]] || die "Could not get IP for ${VM_WORKERS[1]}"

  info "master  : $MASTER_IP"
  info "worker1 : ${WORKER_IPS[0]}"
  info "worker2 : ${WORKER_IPS[1]}"
}

# ── cluster.conf generation ───────────────────────────────────────────────────
write_test_conf() {
  section "Writing $TEST_CONF"
  cat > "$TEST_CONF" <<EOF
# Auto-generated by test-local.sh — do not edit by hand.
CLUSTER_NAME="hc-test"
KUBESPRAY_VERSION="v2.31.0"
KUBE_VERSION="v1.35.4"
CONTAINER_MANAGER="podman"
CNI_PLUGIN="calico"

KUBE_PODS_SUBNET="10.233.64.0/18"
KUBE_SERVICE_ADDRESSES="10.233.0.0/18"

SSH_USER="root"
SSH_KEY="$SSH_KEY"
SSH_EXTRA_ARGS="-o StrictHostKeyChecking=no"

CONTROL_PLANE_IPS="$MASTER_IP"
WORKER_IPS="${WORKER_IPS[0]} ${WORKER_IPS[1]}"

METRICS_SERVER_ENABLED="true"
INGRESS_NGINX_ENABLED="false"
DASHBOARD_ENABLED="false"

KUBECONFIG_OUTPUT="\$HOME/.kube/hc-test.yaml"
EOF
  info "Config written: $TEST_CONF"
}

# ── deploy ────────────────────────────────────────────────────────────────────
run_deploy() {
  section "Running hypercluster deploy"
  cd "$REPO_DIR"
  bash hypercluster -c "$TEST_CONF" deploy
}

# ── verify ────────────────────────────────────────────────────────────────────
verify_cluster() {
  section "Verifying cluster"
  local kc="$HOME/.kube/hc-test.yaml"
  [[ -f "$kc" ]] || die "kubeconfig not found: $kc"

  info "Nodes:"
  KUBECONFIG="$kc" kubectl get nodes -o wide

  info "System pods:"
  KUBECONFIG="$kc" kubectl get pods -n kube-system

  local not_ready
  not_ready=$(KUBECONFIG="$kc" kubectl get nodes --no-headers \
                | grep -cv " Ready " || true)
  if [[ "$not_ready" -gt 0 ]]; then
    warn "$not_ready node(s) not yet Ready — cluster may still be converging."
  else
    info "All nodes Ready. 🎉"
  fi
}

# ── clean ─────────────────────────────────────────────────────────────────────
clean() {
  section "Destroying test VMs and config"
  for vm in "$VM_MASTER" "${VM_WORKERS[@]}"; do
    if vm_exists "$vm"; then
      info "Deleting VM: $vm"
      multipass delete "$vm" --purge
    else
      info "VM not found (already gone): $vm"
    fi
  done
  [[ -f "$TEST_CONF" ]] && { rm -f "$TEST_CONF"; info "Removed $TEST_CONF"; }
  local kc="$HOME/.kube/hc-test.yaml"
  [[ -f "$kc" ]] && { rm -f "$kc"; info "Removed $kc"; }
  info "Clean done."
}

# ── main ──────────────────────────────────────────────────────────────────────
case "${1:-}" in
  --clean)
    clean
    exit 0
    ;;
  --vms-only)
    check_prereqs
    ensure_ssh_key
    create_vms
    get_ips
    section "VMs ready — IPs"
    info "MASTER:  $MASTER_IP"
    for i in "${!VM_WORKERS[@]}"; do
      info "WORKER$((i+1)): ${WORKER_IPS[$i]}"
    done
    info "SSH test: ssh -i $SSH_KEY root@$MASTER_IP hostname"
    exit 0
    ;;
  --help|-h)
    grep '^#' "$0" | grep -v '^#!/' | sed 's/^# \{0,1\}//'
    exit 0
    ;;
  "")
    check_prereqs
    ensure_ssh_key
    create_vms
    get_ips
    write_test_conf
    run_deploy
    verify_cluster

    section "Done"
    info "Cluster deployed and verified! 🎉"
    info ""
    info "Use it:"
    printf "    export KUBECONFIG=\$HOME/.kube/hc-test.yaml\n"
    printf "    kubectl get nodes\n\n"
    info "Tear it down:"
    printf "    ./scripts/test-local.sh --clean\n\n"
    ;;
  *)
    die "Unknown argument: $1  (try --help)"
    ;;
esac
