./hypercluster -c cluster.conf health --json 2>/dev/null
./hypercluster -c cluster.conf test --json 2>/dev/null
make docs
```

## CLI help

```text
{cli_out}```
"""
gen.mkdir(parents=True, exist_ok=True)
(gen / "AGENT-QUICKREF.md").write_text(content, encoding="utf-8")
print("  wrote docs/generated/AGENT-QUICKREF.md")
PY
}

