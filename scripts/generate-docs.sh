#!/usr/bin/env bash
# Generate documentation from repo sources (hyper2kvm-style: _build/, guides, welcome.html).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DOCS="${ROOT}/docs"
BUILD="${DOCS}/_build"
GEN="${DOCS}/generated"
HC="${ROOT}/hypercluster"
VERSION="$(cat "${ROOT}/VERSION" 2>/dev/null || echo unknown)"
TS="$(date -u +"%Y-%m-%dT%H:%M:%SZ")"

mkdir -p "${BUILD}" "${GEN}" "${DOCS}/client-presentations"

gen_cli_txt() {
  "${HC}" -h > "${BUILD}/cli-reference.txt"
  echo "  wrote docs/_build/cli-reference.txt"
}

gen_cli_md() {
  {
    cat <<EOF
<!-- Generated by scripts/generate-docs.sh — do not edit by hand. -->
<!-- Source: hypercluster -h · generated: ${TS} · version: ${VERSION} -->

EOF
    echo "# CLI reference"
    echo
    echo "Plain-text help also at [\`_build/cli-reference.txt\`](../_build/cli-reference.txt)."
    echo
    echo "Machine-readable flags:"
    echo
    echo "| Command | Flag | Output |"
    echo "|---------|------|--------|"
    echo "| \`preflight\` | \`--json\` | Preflight checks JSON |"
    echo "| \`test\` | \`--json\` | JSON on stdout (logs on stderr) |"
    echo "| \`test\` | \`--full\` | Extended snapshot API checks |"
    echo "| \`status\` | \`--json\` | Node readiness JSON |"
    echo
    echo '```text'
    cat "${BUILD}/cli-reference.txt"
    echo '```'
  } > "${GEN}/CLI.md"
  echo "  wrote docs/generated/CLI.md"
}

gen_config() {
  ROOT="${ROOT}" CONFIG_EXAMPLE="${ROOT}/config/cluster.conf.example" \
    VERSION="${VERSION}" TS="${TS}" python3 <<'PY' > "${GEN}/CONFIG-REFERENCE.md"
import os, re
from pathlib import Path

example = Path(os.environ["CONFIG_EXAMPLE"])
version = os.environ.get("VERSION", "unknown")
ts = os.environ["TS"]

lines = example.read_text().splitlines()
sections = []
current = {"title": "Overview", "items": []}
after_divider = False

for line in lines:
    if re.match(r"^# -+$", line):
        after_divider = True
        continue
    m = re.match(r"^# (.+)$", line)
    if m and after_divider:
        title = m.group(1).strip()
        if title and not title.startswith("hypercluster"):
            if current["items"]:
                sections.append(current)
            current = {"title": title, "items": []}
        after_divider = False
        continue
    after_divider = False
    m = re.match(r'^([A-Z_0-9]+)=(".*?"|\S*)\s*(#.*)?$', line.strip())
    if m:
        key, val, comment = m.group(1), m.group(2), (m.group(3) or "").lstrip("# ").strip()
        current["items"].append((key, val.strip('"'), comment))

if current["items"]:
    sections.append(current)

print(f"<!-- Generated by scripts/generate-docs.sh — do not edit by hand. -->")
print(f"<!-- Source: config/cluster.conf.example · generated: {ts} · version: {version} -->")
print()
print("# Configuration reference")
print()
print("Copy [`config/cluster.conf.example`](../../config/cluster.conf.example) to `cluster.conf`.")
print()
print("## k3s platform notes")
print()
print("- `K8S_DISTRO=\"k3s\"` for remote lightweight path.")
print("- Include `--disable-kube-proxy` in `K3S_EXEC_ARGS` with Cilium.")
print("- Install order: **Cilium → cert-manager → MetalLB → KubeVirt/CDI → metrics-server**.")
print("- Healthy re-deploy skips k3s reinstall (`FORCE_K3S_REINSTALL=1` to replace).")
print("- Tested: KubeVirt **v1.8.x** on k8s **v1.35.x** (k3s).")
print()

for sec in sections:
    print(f"## {sec['title']}")
    print()
    print("| Variable | Default | Notes |")
    print("|----------|---------|-------|")
    for key, val, comment in sec["items"]:
        display = val if val else "_empty_"
        display = display.replace("|", "\\|")
        note = comment.replace("|", "\\|")
        print(f"| `{key}` | `{display}` | {note} |")
    print()
PY
  echo "  wrote docs/generated/CONFIG-REFERENCE.md"
}

gen_make() {
  {
    cat <<EOF
<!-- Generated by scripts/generate-docs.sh · ${TS} · v${VERSION} -->

EOF
    echo "# Make targets"
    echo
    echo '```text'
    make -C "${ROOT}" help
    echo '```'
  } > "${GEN}/MAKE-TARGETS.md"
  echo "  wrote docs/generated/MAKE-TARGETS.md"
}

gen_agent_quickref() {
  ROOT="${ROOT}" GEN="${GEN}" HC="${HC}" VERSION="${VERSION}" TS="${TS}" python3 <<'PY'
import os, subprocess
from pathlib import Path

root = Path(os.environ["ROOT"])
gen = Path(os.environ["GEN"])
hc = Path(os.environ["HC"])
version = os.environ["VERSION"]
ts = os.environ["TS"]

libs = sorted(p.name for p in (root / "lib").glob("*.sh"))
tests = sorted(p.name for p in (root / "tests").glob("*.sh"))
cli_out = subprocess.run([str(hc), "-h"], capture_output=True, text=True, check=True).stdout

content = f"""<!-- Generated by scripts/generate-docs.sh — do not edit by hand. -->
<!-- Train agents: AGENTS.md · docs/agents/training.md · {ts} · v{version} -->

# Agent quick reference (generated)

| Resource | Path |
|----------|------|
| Root summary | [AGENTS.md](../../AGENTS.md) |
| Full training | [docs/agents/training.md](../agents/training.md) |
| Cursor rules | [.cursor/rules/](../../.cursor/rules/) |

## Invariants

1. Single config: `cluster.conf` (see `config/cluster.conf.example`).
2. k3s stack: **Cilium → cert-manager → MetalLB → KubeVirt/CDI → metrics-server**.
3. `K3S_EXEC_ARGS` includes `--disable-kube-proxy` with Cilium.
4. Re-deploy skips healthy k3s reinstall; `FORCE_K3S_REINSTALL=1` to replace.
5. `test --json` / `status --json` / `health --json`: stdout JSON only.
6. Desktop spawns `hypercluster` only for lifecycle ops; `hc_health_json` + optional `ai_chat_cmd` for read/chat.

## lib/

{chr(10).join("- `" + x + "`" for x in libs)}

## tests/

{chr(10).join("- `" + x + "`" for x in tests)}

## Agent verify loop

```bash
