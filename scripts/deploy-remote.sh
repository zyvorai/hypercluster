#!/usr/bin/env bash
# deploy-remote.sh — Create 2 libvirt VMs on a remote hypervisor and deploy k3s (1 CP + 1 worker).
#
# Usage:
#   ./scripts/deploy-remote.sh sus 175.110.114.93
#   ./scripts/deploy-remote.sh sus@175.110.114.93
#   ./scripts/deploy-remote.sh sus 175.110.114.93 --vms-only
#   ./scripts/deploy-remote.sh sus 175.110.114.93 --clean
#
# Env: HYPERVISOR SSH_KEY CLUSTER_NAME METALLB_IP_POOL VM_CPUS VM_MEM VM_DISK
set -euo pipefail

if [[ "$(uname)" == "Darwin" && "${BASH_VERSINFO[0]:-3}" -lt 4 ]]; then
  _b="$(brew --prefix 2>/dev/null)/bin/bash"
  [[ -x "$_b" ]] && exec "$_b" "$0" "$@"
  echo "bash 4+ required — run: brew install bash" >&2
  exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
# shellcheck source=lib/log.sh
source "$REPO_DIR/lib/log.sh"
# shellcheck source=lib/deploy-remote-libvirt.sh
source "$SCRIPT_DIR/lib/deploy-remote-libvirt.sh"

HC="$REPO_DIR/hypercluster"
REMOTE_CONF="$REPO_DIR/cluster-remote.conf"
KUBECONFIG_OUT="${KUBECONFIG_OUTPUT:-$HOME/.kube/hc-remote.yaml}"

VM_CP="${VM_CP:-hc-cp-1}"
VM_WORKER="${VM_WORKER:-hc-worker-1}"
VM_CPUS="${VM_CPUS:-2}"
VM_MEM="${VM_MEM:-3072}"
VM_DISK="${VM_DISK:-20}"
CLUSTER_NAME="${CLUSTER_NAME:-hc-remote}"
SSH_USER_GUEST="${SSH_USER_GUEST:-ubuntu}"

DEPLOY_REMOTE_SSH_KEY="${SSH_KEY:-}"
MODE="deploy"
HYPERVISOR="${HYPERVISOR:-}"
HYPERVISOR_JUMP=""   # user@host for ProxyJump to libvirt guests

usage() {
  sed -n '2,12p' "$0"
  cat <<'EOF'

Examples:
  ./scripts/deploy-remote.sh sus 175.110.114.93
  ./scripts/deploy-remote.sh sus@175.110.114.93 --vms-only
  METALLB_IP_POOL=192.168.122.240-192.168.122.250 ./scripts/deploy-remote.sh sus@host

Env: HYPERVISOR SSH_KEY CLUSTER_NAME METALLB_IP_POOL VM_CPUS VM_MEM VM_DISK
EOF
  exit 0
}

parse_target() {
  local a="${1:-}" b="${2:-}"
  if [[ -z "$a" ]]; then
    [[ -n "$HYPERVISOR" ]] || { usage; exit 1; }
    HYPERVISOR_JUMP="$HYPERVISOR"
    return 0
  fi
  if [[ "$a" == *@* ]]; then
    HYPERVISOR="$a"
    HYPERVISOR_JUMP="$a"
    return 0
  fi
  if [[ -n "$b" && "$b" != -* ]]; then
    HYPERVISOR="${a}@${b}"
    HYPERVISOR_JUMP="${a}@${b}"
    return 0
  fi
  if [[ "$a" =~ ^[0-9.]+$ ]]; then
    HYPERVISOR="${USER}@${a}"
    HYPERVISOR_JUMP="${USER}@${a}"
    return 0
  fi
  die "usage: deploy-remote.sh USER HOST | USER@HOST [--vms-only|--clean]"
}

ensure_ssh_key() {
  if [[ -n "$DEPLOY_REMOTE_SSH_KEY" && -f "$DEPLOY_REMOTE_SSH_KEY" ]]; then
    return 0
  fi
  for candidate in "$HOME/.ssh/id_ed25519" "$HOME/.ssh/id_rsa"; do
    if [[ -f "$candidate" ]]; then
      DEPLOY_REMOTE_SSH_KEY="$candidate"
      return 0
    fi
  done
  DEPLOY_REMOTE_SSH_KEY="$HOME/.ssh/id_hypercluster_remote"
  if [[ ! -f "$DEPLOY_REMOTE_SSH_KEY" ]]; then
    log::section "Generating SSH key for guest VMs"
    ssh-keygen -t ed25519 -f "$DEPLOY_REMOTE_SSH_KEY" -C "hypercluster-remote" -N ""
    chmod 600 "$DEPLOY_REMOTE_SSH_KEY"
  fi
}

write_cluster_conf() {
  local cp_ip="$1" worker_ip="$2" pool="$3"
  log::section "Writing $REMOTE_CONF"
  cat > "$REMOTE_CONF" <<EOF
# Auto-generated by scripts/deploy-remote.sh — do not edit by hand.
CLUSTER_NAME="${CLUSTER_NAME}"

K8S_DISTRO="k3s"
K3S_DATA_DIR="/data/k3s"
K3S_VERSION=""
K3S_EXEC_ARGS="--flannel-backend=none --disable-network-policy --disable traefik --disable servicelb --disable-kube-proxy"
CILIUM_HUBBLE_ENABLED="true"
CILIUM_KUBE_PROXY_REPLACEMENT="true"
CILIUM_BGP_ENABLED="false"
CILIUM_WIREGUARD_ENABLED="false"
CILIUM_GATEWAY_API_ENABLED="false"
CILIUM_K8S_SERVICE_HOST="${cp_ip}"

PLATFORM_STACK_ENABLED="true"
CERT_MANAGER_ENABLED="true"
METALLB_ENABLED="true"
METALLB_IP_POOL="${pool}"
CDI_ENABLED="true"
KUBEVIRT_CSI_ENABLED="true"
KUBEVIRT_DISKS_PROVIDER="true"
SNAPSHOT_CONTROLLER_ENABLED="true"
CNAO_ENABLED="true"
SSP_ENABLED="true"
LONGHORN_ENABLED="false"

KUBE_PODS_SUBNET="10.42.0.0/16"
KUBE_SERVICE_ADDRESSES="10.43.0.0/16"

SSH_USER="${SSH_USER_GUEST}"
SSH_KEY="${DEPLOY_REMOTE_SSH_KEY}"
SSH_PORT=22
SSH_EXTRA_ARGS="-o StrictHostKeyChecking=accept-new -o ProxyJump=${HYPERVISOR_JUMP}"
SSH_PROXY_JUMP="${HYPERVISOR_JUMP}"

CONTROL_PLANE_IPS="${cp_ip}"
WORKER_IPS="${worker_ip}"

KUBEVIRT_ENABLED="true"
KUBEVIRT_VERSION="v1.8.3"
CDI_VERSION="v1.65.0"
METRICS_SERVER_ENABLED="true"

KUBECONFIG_OUTPUT="${KUBECONFIG_OUT}"
KUBECONFIG_MERGE_DEFAULT="false"
K3S_API_LOCAL_PORT="16443"
EOF
  log::info "Config: control-plane=$cp_ip worker=$worker_ip MetalLB=$pool"
}

wait_guest_ssh() {
  local ip="$1"
  local tries=0
  local ssh_opts=(
    -o BatchMode=yes
    -o ConnectTimeout=10
    -o StrictHostKeyChecking=accept-new
    -o "ProxyJump=${HYPERVISOR_JUMP}"
    -i "$DEPLOY_REMOTE_SSH_KEY"
  )
  log::info "Waiting for SSH on $ip (via ${HYPERVISOR_JUMP}) …"
  while (( tries < 36 )); do
    if ssh "${ssh_opts[@]}" "${SSH_USER_GUEST}@${ip}" 'echo ok' >/dev/null 2>&1; then
      log::ok "SSH ready on $ip"
      return 0
    fi
    (( tries++ )) || true
    sleep 5
  done
  die "SSH not reachable on ${SSH_USER_GUEST}@${ip} (via ${HYPERVISOR_JUMP})"
}

create_vms() {
  local pubkey cp_ip worker_ip pool
  pubkey="$(cat "${DEPLOY_REMOTE_SSH_KEY}.pub")"

  log::section "Hypervisor preflight ($HYPERVISOR)"
  deploy_remote_libvirt::check_hypervisor "$HYPERVISOR"
  log::ok "libvirtd + default network OK"

  if [[ -z "${METALLB_IP_POOL:-}" ]]; then
    pool="$(deploy_remote_libvirt::detect_metallb_pool "$HYPERVISOR" 2>/dev/null || true)"
    [[ -n "$pool" ]] || die "Set METALLB_IP_POOL (could not detect libvirt default subnet on $HYPERVISOR)"
    METALLB_IP_POOL="$pool"
  fi
  log::info "MetalLB pool: $METALLB_IP_POOL"

  log::section "Creating control-plane VM ($VM_CP)"
  deploy_remote_libvirt::ensure_vm "$HYPERVISOR" "$VM_CP" "$pubkey" "$VM_CPUS" "$VM_MEM" "$VM_DISK"
  cp_ip="$(deploy_remote_libvirt::wait_vm_ip "$HYPERVISOR" "$VM_CP")"
  log::ok "$VM_CP → $cp_ip"

  log::section "Creating worker VM ($VM_WORKER)"
  deploy_remote_libvirt::ensure_vm "$HYPERVISOR" "$VM_WORKER" "$pubkey" "$VM_CPUS" "$VM_MEM" "$VM_DISK"
  worker_ip="$(deploy_remote_libvirt::wait_vm_ip "$HYPERVISOR" "$VM_WORKER")"
  log::ok "$VM_WORKER → $worker_ip"

  wait_guest_ssh "$cp_ip"
  wait_guest_ssh "$worker_ip"

  write_cluster_conf "$cp_ip" "$worker_ip" "$METALLB_IP_POOL"

  log::section "VM summary"
  log::info "Control plane: ${SSH_USER_GUEST}@${cp_ip} ($VM_CP)"
  log::info "Worker:        ${SSH_USER_GUEST}@${worker_ip} ($VM_WORKER)"
}

run_deploy() {
  [[ -x "$HC" ]] || die "$HC not executable — run: chmod +x hypercluster"
  local cp_ip tunnel_port=16443
  cp_ip="$(grep '^CONTROL_PLANE_IPS=' "$REMOTE_CONF" 2>/dev/null | cut -d'"' -f2 || true)"
  [[ -n "$cp_ip" ]] || die "control plane IP missing in $REMOTE_CONF"
  log::section "SSH API tunnel (127.0.0.1:${tunnel_port} → ${cp_ip}:6443 via ${HYPERVISOR_JUMP})"
  deploy_remote_libvirt::start_api_tunnel "$cp_ip" "$HYPERVISOR_JUMP" "$tunnel_port" \
    || die "API tunnel failed — cannot reach k3s from laptop"
  log::ok "API tunnel up"
  trap "deploy_remote_libvirt::stop_api_tunnel ${tunnel_port} ${cp_ip}" EXIT

  log::section "hypercluster preflight"
  "$HC" -c "$REMOTE_CONF" preflight
  log::section "hypercluster deploy"
  "$HC" -c "$REMOTE_CONF" deploy
  log::section "hypercluster test"
  if "$HC" -c "$REMOTE_CONF" test --json 2>/dev/null; then
    log::ok "Platform smoke passed"
  else
    log::warn "test --json reported failures — check cluster manually"
  fi
}

clean() {
  log::section "Removing libvirt VMs on $HYPERVISOR"
  deploy_remote_libvirt::destroy_vms "$HYPERVISOR" "$VM_CP" "$VM_WORKER"
  [[ -f "$REMOTE_CONF" ]] && rm -f "$REMOTE_CONF" && log::info "Removed $REMOTE_CONF"
  [[ -f "$KUBECONFIG_OUT" ]] && rm -f "$KUBECONFIG_OUT" && log::info "Removed $KUBECONFIG_OUT"
  log::ok "Clean done"
}

# ── args ──────────────────────────────────────────────────────────────────────
POSITIONAL=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help) usage ;;
    --vms-only) MODE="vms-only"; shift ;;
    --clean) MODE="clean"; shift ;;
    --*) die "Unknown option: $1" ;;
    *) POSITIONAL+=("$1"); shift ;;
  esac
done

if [[ ${#POSITIONAL[@]} -ge 1 ]]; then
  parse_target "${POSITIONAL[0]:-}" "${POSITIONAL[1]:-}"
elif [[ -z "$HYPERVISOR" ]]; then
  usage
fi

ensure_ssh_key

case "$MODE" in
  clean)
    clean
    ;;
  vms-only)
    create_vms
    log::ok "VMs ready — deploy with: ./hypercluster -c cluster-remote.conf deploy"
    ;;
  deploy)
    create_vms
    run_deploy
    log::section "Done"
    log::info "Kubeconfig: $KUBECONFIG_OUT"
    printf '  export KUBECONFIG=%q\n' "$KUBECONFIG_OUT"
    printf '  ./hypercluster -c %q status --json\n' "$REMOTE_CONF"
    ;;
esac
