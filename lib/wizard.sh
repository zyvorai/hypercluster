#!/usr/bin/env bash
# Interactive cluster.conf generator — source this file.

wizard::_prompt() {
  local var_name="$1" prompt="$2" default="${3:-}"
  local input
  if [[ -n "$default" ]]; then
    read -r -p "$prompt [$default]: " input
    input="${input:-$default}"
  else
    while [[ -z "${input:-}" ]]; do
      read -r -p "$prompt: " input
      [[ -n "$input" ]] || log::warn "Value required."
    done
  fi
  printf -v "$var_name" '%s' "$input"
}

wizard::_prompt_yn() {
  local var_name="$1" prompt="$2" default="${3:-n}"
  local input
  read -r -p "$prompt [y/N]: " input
  input="${input:-$default}"
  if [[ "$input" =~ ^[Yy] ]]; then
    printf -v "$var_name" '%s' "true"
  else
    printf -v "$var_name" '%s' "false"
  fi
}

wizard::_valid_ip_list() {
  local ips="$1"
  local ip
  for ip in $ips; do
    [[ "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || return 1
  done
  [[ -n "$ips" ]]
}

wizard::_choose_distro() {
  echo ""
  echo "  Kubernetes distribution:"
  echo "    1) kubespray  (upstream kubeadm, HA-capable)"
  echo "    2) k3s        (remote single/multi-node + platform stack)"
  local choice
  wizard::_prompt choice "Choose" "2"
  case "$choice" in
    1) echo "kubespray" ;;
    2|"") echo "k3s" ;;
    *) log::warn "Unknown choice — using k3s."; echo "k3s" ;;
  esac
}

wizard::_choose_cni() {
  echo ""
  echo "  CNI plugin:"
  echo "    1) cilium   (default)"
  echo "    2) calico"
  echo "    3) flannel"
  echo "    4) kube-ovn"
  local choice
  wizard::_prompt choice "Choose" "1"
  case "$choice" in
    1|"") echo "cilium" ;;
    2)    echo "calico" ;;
    3)    echo "flannel" ;;
    4)    echo "kube-ovn" ;;
    *)    log::warn "Unknown choice — using cilium."; echo "cilium" ;;
  esac
}

wizard::_choose_runtime() {
  echo ""
  echo "  Container runtime:"
  echo "    1) podman      (default)"
  echo "    2) containerd"
  echo "    3) docker"
  local choice
  wizard::_prompt choice "Choose" "1"
  case "$choice" in
    1|"") echo "podman" ;;
    2)    echo "containerd" ;;
    3)    echo "docker" ;;
    *)    log::warn "Unknown choice — using podman."; echo "podman" ;;
  esac
}

wizard::write_config() {
  local dest="$1"
  local cluster_name cp_ips worker_ips ssh_user ssh_key cni runtime kubevirt distro metallb_pool
  local default_key="$HOME/.ssh/id_rsa"

  log::section "Cluster configuration wizard"
  echo "Creates: $dest"
  echo ""

  if [[ -f "$dest" ]]; then
    local overwrite
    wizard::_prompt overwrite "Config exists. Overwrite? (y/N)" "n"
    [[ "$overwrite" =~ ^[Yy] ]] || die "Wizard aborted — config unchanged."
  fi

  wizard::_prompt cluster_name "Cluster name" "mycluster"
  distro=$(wizard::_choose_distro)

  while true; do
    wizard::_prompt cp_ips "Control-plane IPs (space-separated)" "192.168.1.100"
    wizard::_valid_ip_list "$cp_ips" && break
    log::warn "Enter one or more valid IPv4 addresses."
  done

  wizard::_prompt worker_ips "Worker IPs (space-separated, or leave empty for single-node)" ""

  wizard::_prompt ssh_user "SSH user" "root"
  wizard::_prompt ssh_key "SSH private key path" "$default_key"
  ssh_key="${ssh_key/#\~/$HOME}"
  [[ -f "$ssh_key" ]] || die "SSH key not found: $ssh_key"

  cni=$(wizard::_choose_cni)
  if [[ "$distro" == "kubespray" ]]; then
    runtime=$(wizard::_choose_runtime)
  else
    runtime="containerd"
  fi

  wizard::_prompt_yn kubevirt "Install KubeVirt platform stack?" "y"

  if [[ "$distro" == "k3s" ]]; then
    wizard::_prompt metallb_pool "MetalLB IP pool (required for k3s)" "192.168.1.240-192.168.1.250"
  else
    metallb_pool=""
  fi

  mkdir -p "$(dirname "$dest")"
  if [[ "$distro" == "k3s" ]]; then
    cat > "$dest" <<EOF
# Generated by hypercluster wizard — $(date -u +%Y-%m-%dT%H:%M:%SZ)
CLUSTER_NAME="$cluster_name"

K8S_DISTRO="k3s"
K3S_DATA_DIR="/data/k3s"
K3S_EXEC_ARGS="--flannel-backend=none --disable-network-policy --disable traefik --disable servicelb --disable-kube-proxy"
CILIUM_K8S_SERVICE_HOST="127.0.0.1"

PLATFORM_STACK_ENABLED="true"
METALLB_ENABLED="true"
METALLB_IP_POOL="$metallb_pool"
KUBEVIRT_DISKS_PROVIDER="true"

KUBE_PODS_SUBNET="10.42.0.0/16"
KUBE_SERVICE_ADDRESSES="10.43.0.0/16"
CNI_PLUGIN="$cni"

SSH_USER="$ssh_user"
SSH_KEY="$ssh_key"
SSH_PORT=22
SSH_EXTRA_ARGS=""

CONTROL_PLANE_IPS="$cp_ips"
WORKER_IPS="$worker_ips"

KUBEVIRT_ENABLED="$kubevirt"
KUBEVIRT_VERSION="v1.8.3"
CDI_VERSION="v1.65.0"
METRICS_SERVER_ENABLED="true"

KUBECONFIG_OUTPUT="\$HOME/.kube/${cluster_name}.yaml"
KUBECONFIG_MERGE_DEFAULT="false"
EOF
  else
    cat > "$dest" <<EOF
# Generated by hypercluster wizard — $(date -u +%Y-%m-%dT%H:%M:%SZ)
CLUSTER_NAME="$cluster_name"

K8S_DISTRO="kubespray"
KUBESPRAY_VERSION="v2.31.0"
KUBESPRAY_DIR=".kubespray"

KUBE_VERSION="v1.35.4"
CONTAINER_MANAGER="$runtime"
CNI_PLUGIN="$cni"

KUBE_PODS_SUBNET="10.233.64.0/18"
KUBE_SERVICE_ADDRESSES="10.233.0.0/18"

SSH_USER="$ssh_user"
SSH_KEY="$ssh_key"
SSH_PORT=22
SSH_EXTRA_ARGS=""

CONTROL_PLANE_IPS="$cp_ips"
WORKER_IPS="$worker_ips"

METRICS_SERVER_ENABLED="true"
INGRESS_NGINX_ENABLED="false"
DASHBOARD_ENABLED="false"

KUBEVIRT_ENABLED="$kubevirt"
KUBEVIRT_VERSION="v1.3.1"
CDI_VERSION="v1.59.0"

KUBECONFIG_OUTPUT="\$HOME/.kube/${cluster_name}.yaml"
EOF
  fi

  log::ok "Wrote $dest"
  echo ""
  log::info "Next steps:"
  printf "    ./hypercluster -c %s preflight\n" "$dest"
  printf "    ./hypercluster -c %s deploy\n" "$dest"
  if [[ "$distro" == "k3s" ]]; then
    printf "    ./hypercluster -c %s test\n" "$dest"
  fi
  echo ""
}

wizard::run() {
  local dest="$1" run_init="${2:-0}"
  wizard::write_config "$dest"
  if [[ "$run_init" == "1" ]]; then
    log::info "Continuing to init …"
  fi
}
