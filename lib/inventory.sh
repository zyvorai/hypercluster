#!/usr/bin/env bash
# Inventory + group_vars generation — source this file, do not execute directly.

inventory::_node_entry() {
  local name="$1" ip="$2"
  printf "    %s:\n      ansible_host: %s\n      ip: %s\n      access_ip: %s\n" \
    "$name" "$ip" "$ip" "$ip"
  # Emit ansible_port only when SSH_PORT is set and non-standard
  if [[ -n "${SSH_PORT:-}" && "${SSH_PORT}" != "22" ]]; then
    printf "      ansible_port: %s\n" "${SSH_PORT}"
  fi
}

inventory::generate_hosts_yaml() {
  local dest_dir="$1"
  local cp_ips=($CONTROL_PLANE_IPS)
  local worker_ips=($WORKER_IPS)

  log::section "Generating inventory"
  mkdir -p "$dest_dir"

  local hosts_file="$dest_dir/hosts.yaml"

  {
    echo "all:"
    echo "  hosts:"

    local idx=1
    for ip in "${cp_ips[@]}"; do
      inventory::_node_entry "master${idx}" "$ip"
      (( idx++ ))
    done

    idx=1
    for ip in "${worker_ips[@]}"; do
      inventory::_node_entry "worker${idx}" "$ip"
      (( idx++ ))
    done

    echo "  children:"

    # kube_control_plane
    echo "    kube_control_plane:"
    echo "      hosts:"
    idx=1
    for _ in "${cp_ips[@]}"; do
      echo "        master${idx}:"
      (( idx++ ))
    done

    # kube_node (workers — control-plane nodes are excluded from workloads by default)
    echo "    kube_node:"
    echo "      hosts:"
    idx=1
    for _ in "${worker_ips[@]}"; do
      echo "        worker${idx}:"
      (( idx++ ))
    done

    # etcd — co-located on control-plane nodes
    echo "    etcd:"
    echo "      hosts:"
    idx=1
    for _ in "${cp_ips[@]}"; do
      echo "        master${idx}:"
      (( idx++ ))
    done

    echo "    k8s_cluster:"
    echo "      children:"
    echo "        kube_control_plane:"
    echo "        kube_node:"

    echo "    calico_rr:"
    echo "      hosts: {}"

  } > "$hosts_file"

  log::ok "hosts.yaml written → $hosts_file"
}

inventory::generate_group_vars() {
  local dest_dir="$1"
  local cluster_dir="$dest_dir/group_vars/k8s_cluster"
  local all_dir="$dest_dir/group_vars/all"

  mkdir -p "$cluster_dir" "$all_dir"

  # --- k8s-cluster.yml ---
  cat > "$cluster_dir/k8s-cluster.yml" <<EOF
# Generated by hypercluster — do not edit by hand.
kube_version: ${KUBE_VERSION}
container_manager: ${CONTAINER_MANAGER}
kube_network_plugin: ${CNI_PLUGIN:-cilium}
kube_network_plugin_multus: false

kube_service_addresses: ${KUBE_SERVICE_ADDRESSES}
kube_pods_subnet: ${KUBE_PODS_SUBNET}

# Required for Podman rootful mode
kubelet_cgroup_driver: systemd

# kubeconfig stored locally after fetch
kubeconfig_localhost: true
EOF
  log::ok "k8s-cluster.yml written"

  # --- addons.yml ---
  cat > "$cluster_dir/addons.yml" <<EOF
# Generated by hypercluster — do not edit by hand.
metrics_server_enabled: ${METRICS_SERVER_ENABLED:-true}
ingress_nginx_enabled: ${INGRESS_NGINX_ENABLED:-false}
dashboard_enabled: ${DASHBOARD_ENABLED:-false}
EOF
  log::ok "addons.yml written"

  # --- all.yml (SSH / misc) ---
  cat > "$all_dir/all.yml" <<EOF
# Generated by hypercluster — do not edit by hand.
ansible_user: ${SSH_USER}
ansible_ssh_private_key_file: ${SSH_KEY/#\~/$HOME}
ansible_become: true
EOF
  log::ok "all.yml written"
}

inventory::init() {
  local kubespray_dir="$1"
  local inv_dest="$kubespray_dir/inventory/$CLUSTER_NAME"
  local sample_dir="$kubespray_dir/inventory/sample"

  [[ -d "$sample_dir" ]] || die "Kubespray sample inventory not found: $sample_dir — is the clone complete?"

  if [[ -d "$inv_dest" ]]; then
    if [[ "${FORCE:-0}" != "1" ]]; then
      die "Inventory already exists: $inv_dest
       Re-run with -f to overwrite, or delete it manually."
    fi
    log::warn "Overwriting existing inventory (--force): $inv_dest"
    rm -rf "$inv_dest"
  fi

  cp -r "$sample_dir" "$inv_dest"
  inventory::generate_hosts_yaml "$inv_dest"
  inventory::generate_group_vars "$inv_dest"

  log::ok "Inventory ready at $inv_dest 📋"
}
