import { getConfVar, getConfBool, getConfIps } from './confParse'

function nodeSshOverridesJson(spec: ClusterSpec): string | null {
  const overrides = spec.nodes
    .filter((n) => n.sshUser || n.sshKey || n.sshPort)
    .map((n) => ({
      ip: n.ip,
      ...(n.sshUser ? { sshUser: n.sshUser } : {}),
      ...(n.sshKey ? { sshKey: n.sshKey } : {}),
      ...(n.sshPort ? { sshPort: n.sshPort } : {}),
    }))
  return overrides.length ? JSON.stringify(overrides) : null
}

function nodeLayoutJson(spec: ClusterSpec): string | null {
  const layouts = spec.nodes
    .filter((n) => n.position)
    .map((n) => ({ id: n.id, ip: n.ip, x: n.position!.x, y: n.position!.y }))
  return layouts.length ? JSON.stringify(layouts) : null
}

function parseNodeSshOverrides(content: string): Map<string, Partial<ClusterNode>> {
  const raw = getConfVar(content, 'NODE_SSH_OVERRIDES_JSON')
  const map = new Map<string, Partial<ClusterNode>>()
  if (!raw) return map
  try {
    const arr = JSON.parse(raw) as { ip: string; sshUser?: string; sshKey?: string; sshPort?: number }[]
    for (const o of arr) {
      if (!o.ip) continue
      map.set(o.ip, {
        sshUser: o.sshUser,
        sshKey: o.sshKey,
        sshPort: o.sshPort,
      })
    }
  } catch {
    /* ignore malformed JSON */
  }
  return map
}

function parseNodeLayout(content: string): Map<string, { x: number; y: number }> {
  const raw = getConfVar(content, 'NODE_LAYOUT_JSON')
  const map = new Map<string, { x: number; y: number }>()
  if (!raw) return map
  try {
    const arr = JSON.parse(raw) as { id: string; ip: string; x: number; y: number }[]
    for (const o of arr) {
      const key = o.id || o.ip
      if (key) map.set(key, { x: o.x, y: o.y })
    }
  } catch {
    /* ignore malformed JSON */
  }
  return map
}

