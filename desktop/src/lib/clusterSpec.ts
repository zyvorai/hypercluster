export function syncIpsFromNodes(spec: ClusterSpec): ClusterSpec {
  const cp = spec.nodes.filter((n) => n.roles.includes('control-plane')).map((n) => n.ip)
  const workers = spec.nodes.filter((n) => n.roles.includes('worker')).map((n) => n.ip)
  return {
    ...spec,
    controlPlaneIps: cp.length ? cp : spec.controlPlaneIps,
    workerIps: workers.length ? workers : spec.workerIps,
  }
}

export function syncNodesFromIps(spec: ClusterSpec): ClusterSpec {
  if (spec.nodes.length > 0) return spec
  const nodes: ClusterNode[] = [
    ...spec.controlPlaneIps.map((ip, i) => ({
      id: `cp-${i}`,
      hostname: `cp-${i + 1}`,
      ip,
      roles: ['control-plane'] as NodeRole[],
    })),
    ...spec.workerIps.map((ip, i) => ({
      id: `w-${i}`,
      hostname: `worker-${i + 1}`,
      ip,
      roles: ['worker'] as NodeRole[],
    })),
  ]
  return { ...spec, nodes }
}

export function specToClusterConf(spec: ClusterSpec): string {
  const s = syncIpsFromNodes(syncNodesFromIps(spec))
  const lines: string[] = [
    '# hypercluster cluster configuration',
    '# Generated by Hypercluster Desktop — Cluster Studio',
    '',
    `CLUSTER_NAME="${s.clusterName}"`,
    `K8S_DISTRO="${s.k8sDistro}"`,
    `DEPLOY_MODEL="${s.deployModel}"`,
    '',
    `KUBESPRAY_VERSION="${s.kubesprayVersion}"`,
    `KUBESPRAY_DIR=".kubespray"`,
    `K3S_DATA_DIR="/data/k3s"`,
    `K3S_EXEC_ARGS="--flannel-backend=none --disable-network-policy --disable traefik --disable servicelb --disable-kube-proxy"`,
    `CILIUM_HUBBLE_ENABLED="${s.ciliumHubble ? 'true' : 'false'}"`,
    `CILIUM_KUBE_PROXY_REPLACEMENT="${s.ciliumKubeProxyReplacement ? 'true' : 'false'}"`,
    `CILIUM_BGP_ENABLED="${s.ciliumBgp ? 'true' : 'false'}"`,
    `CILIUM_WIREGUARD_ENABLED="${s.ciliumWireguard ? 'true' : 'false'}"`,
    `CILIUM_GATEWAY_API_ENABLED="${s.ciliumGatewayApi ? 'true' : 'false'}"`,
    `CILIUM_K8S_SERVICE_HOST="127.0.0.1"`,
    `PLATFORM_STACK_ENABLED="${s.platformStackEnabled ? 'true' : 'false'}"`,
    `CERT_MANAGER_ENABLED="${s.certManagerEnabled ? 'true' : 'false'}"`,
    `METALLB_ENABLED="${s.metallbEnabled ? 'true' : 'false'}"`,
    `METALLB_IP_POOL="${s.metallbIpPool}"`,
    `CDI_ENABLED="true"`,
    `KUBEVIRT_CSI_ENABLED="true"`,
    `KUBEVIRT_DISKS_PROVIDER="${s.kubevirtEnabled ? 'true' : 'false'}"`,
    `SNAPSHOT_CONTROLLER_ENABLED="true"`,
    `CNAO_ENABLED="${s.cnaoEnabled ? 'true' : 'false'}"`,
    `SSP_ENABLED="${s.sspEnabled ? 'true' : 'false'}"`,
    `LONGHORN_ENABLED="${s.longhornEnabled ? 'true' : 'false'}"`,
    `GPU_OPERATOR_ENABLED="${s.gpuOperatorEnabled ? 'true' : 'false'}"`,
    `NFD_ENABLED="${s.nfdEnabled ? 'true' : 'false'}"`,
    `INGRESS_NGINX_ENABLED="${s.ingressNginxEnabled ? 'true' : 'false'}"`,
    '',
    `KUBE_VERSION="${s.kubeVersion}"`,
    `CONTAINER_MANAGER="${s.containerManager}"`,
    `CNI_PLUGIN="${s.cniPlugin}"`,
    `KUBE_PODS_SUBNET="${s.kubePodsSubnet}"`,
    `KUBE_SERVICE_ADDRESSES="${s.kubeServiceAddresses}"`,
    '',
    `SSH_USER="${s.sshUser}"`,
    `SSH_KEY="${s.sshKey}"`,
    `SSH_PORT=${s.sshPort}`,
    `SSH_EXTRA_ARGS="-o StrictHostKeyChecking=no"`,
  ]
  if (s.sshProxyJump) lines.push(`SSH_PROXY_JUMP="${s.sshProxyJump}"`)
  const sshOverrides = nodeSshOverridesJson(s)
  if (sshOverrides) lines.push(`NODE_SSH_OVERRIDES_JSON='${sshOverrides}'`)
  const layout = nodeLayoutJson(s)
  if (layout) lines.push(`NODE_LAYOUT_JSON='${layout}'`)
  lines.push(
    '',
    `CONTROL_PLANE_IPS="${s.controlPlaneIps.join(' ')}"`,
    `WORKER_IPS="${s.workerIps.join(' ')}"`,
    '',
    `METRICS_SERVER_ENABLED="${s.metricsServerEnabled ? 'true' : 'false'}"`,
    `KUBEVIRT_ENABLED="${s.kubevirtEnabled ? 'true' : 'false'}"`,
    `KUBEVIRT_VERSION="${s.kubevirtVersion}"`,
    `CDI_VERSION="${s.cdiVersion}"`,
    `KUBECONFIG_OUTPUT="$HOME/.kube/${s.clusterName}.yaml"`,
    `KUBECONFIG_MERGE_DEFAULT="false"`,
  )
  if (s.k8sDistro === 'k3s') {
    lines.push(
      '',
      '# Lab operations (single-node k3s)',
      `LAB_SECONDARY_DISK="${s.labSecondaryDisk}"`,
      `LAB_KUBEVIRT_VOLUME_MOUNT="${s.labKubevirtVolumeMount}"`,
      `LAB_KUBEVIRT_VOLUME_SUBPATH="${s.labKubevirtVolumeMount}/pvc"`,
      `LAB_KUBEVIRT_STORAGE_CLASS="${s.labKubevirtStorageClass}"`,
      `LAB_STORAGE_FORMAT="${s.labStorageFormat ? '1' : '0'}"`,
      `LAB_MEMORY_TUNE_ENABLED="${s.labMemoryTuneEnabled ? 'true' : 'false'}"`,
      `LAB_AUTO_SETUP="${s.labAutoSetup ? 'true' : 'false'}"`,
    )
  }
  if (s.k8sDistro === 'k3s') {
    lines.splice(
      lines.findIndex((l) => l.startsWith('KUBE_VERSION=')) + 1,
      0,
      `K3S_VERSION="${s.kubeVersion}"`,
    )
  }
  return lines.join('\n') + '\n'
}

export function parseClusterSpec(content: string, clusterName?: string): ClusterSpec {
  const base = defaultClusterSpec()
  const distro = (getConfVar(content, 'K8S_DISTRO') || 'k3s') as K8sDistro
  const k3sVer = getConfVar(content, 'K3S_VERSION')
  const kubeVer = getConfVar(content, 'KUBE_VERSION')
  const sshPortRaw = getConfVar(content, 'SSH_PORT')
  const cpIps = getConfIps(content, 'CONTROL_PLANE_IPS')
  const workerIps = getConfIps(content, 'WORKER_IPS')

  const spec: ClusterSpec = {
    ...base,
    templateId: '' as StudioTemplateId,
    clusterName: getConfVar(content, 'CLUSTER_NAME') || clusterName || base.clusterName,
    k8sDistro: distro,
    deployModel: (getConfVar(content, 'DEPLOY_MODEL') || 'ssh') as ClusterSpec['deployModel'],
    kubesprayVersion: getConfVar(content, 'KUBESPRAY_VERSION') || base.kubesprayVersion,
    kubeVersion: k3sVer || kubeVer || base.kubeVersion,
    controlPlaneIps: cpIps,
    workerIps,
    sshUser: getConfVar(content, 'SSH_USER') || base.sshUser,
    sshKey: getConfVar(content, 'SSH_KEY') || base.sshKey,
    sshPort: sshPortRaw ? Number.parseInt(sshPortRaw, 10) || base.sshPort : base.sshPort,
    sshProxyJump: getConfVar(content, 'SSH_PROXY_JUMP'),
    kubePodsSubnet: getConfVar(content, 'KUBE_PODS_SUBNET') || base.kubePodsSubnet,
    kubeServiceAddresses: getConfVar(content, 'KUBE_SERVICE_ADDRESSES') || base.kubeServiceAddresses,
    cniPlugin: getConfVar(content, 'CNI_PLUGIN') || base.cniPlugin,
    containerManager: getConfVar(content, 'CONTAINER_MANAGER') || base.containerManager,
    ciliumHubble: getConfBool(content, 'CILIUM_HUBBLE_ENABLED', base.ciliumHubble),
    ciliumKubeProxyReplacement: getConfBool(content, 'CILIUM_KUBE_PROXY_REPLACEMENT', base.ciliumKubeProxyReplacement),
    ciliumBgp: getConfBool(content, 'CILIUM_BGP_ENABLED', base.ciliumBgp),
    ciliumWireguard: getConfBool(content, 'CILIUM_WIREGUARD_ENABLED', base.ciliumWireguard),
    ciliumGatewayApi: getConfBool(content, 'CILIUM_GATEWAY_API_ENABLED', base.ciliumGatewayApi),
    platformStackEnabled: getConfBool(content, 'PLATFORM_STACK_ENABLED', base.platformStackEnabled),
    metallbEnabled: getConfBool(content, 'METALLB_ENABLED', base.metallbEnabled),
    metallbIpPool: getConfVar(content, 'METALLB_IP_POOL') || base.metallbIpPool,
    longhornEnabled: getConfBool(content, 'LONGHORN_ENABLED', base.longhornEnabled),
    kubevirtEnabled: getConfBool(content, 'KUBEVIRT_ENABLED', base.kubevirtEnabled),
    certManagerEnabled: getConfBool(content, 'CERT_MANAGER_ENABLED', base.certManagerEnabled),
    metricsServerEnabled: getConfBool(content, 'METRICS_SERVER_ENABLED', base.metricsServerEnabled),
    cnaoEnabled: getConfBool(content, 'CNAO_ENABLED', base.cnaoEnabled),
    sspEnabled: getConfBool(content, 'SSP_ENABLED', base.sspEnabled),
    gpuOperatorEnabled: getConfBool(content, 'GPU_OPERATOR_ENABLED', base.gpuOperatorEnabled),
    nfdEnabled: getConfBool(content, 'NFD_ENABLED', base.nfdEnabled),
    ingressNginxEnabled: getConfBool(content, 'INGRESS_NGINX_ENABLED', base.ingressNginxEnabled),
    kubevirtVersion: getConfVar(content, 'KUBEVIRT_VERSION') || base.kubevirtVersion,
    cdiVersion: getConfVar(content, 'CDI_VERSION') || base.cdiVersion,
    nodes: [],
    haControlPlane:
      cpIps.length >= 5 ? '5' : cpIps.length >= 3 ? '3' : cpIps.length === 1 ? 'single' : 'custom',
    labSecondaryDisk: getConfVar(content, 'LAB_SECONDARY_DISK') || base.labSecondaryDisk,
    labKubevirtVolumeMount:
      getConfVar(content, 'LAB_KUBEVIRT_VOLUME_MOUNT') || base.labKubevirtVolumeMount,
    labKubevirtStorageClass:
      getConfVar(content, 'LAB_KUBEVIRT_STORAGE_CLASS') || base.labKubevirtStorageClass,
    labStorageFormat: getConfVar(content, 'LAB_STORAGE_FORMAT') === '1',
    labMemoryTuneEnabled: getConfBool(content, 'LAB_MEMORY_TUNE_ENABLED', base.labMemoryTuneEnabled),
    labAutoSetup: getConfBool(content, 'LAB_AUTO_SETUP', base.labAutoSetup),
  }
  const sshMap = parseNodeSshOverrides(content)
  const layoutMap = parseNodeLayout(content)
  const withNodes = syncNodesFromIps(spec)
  if (sshMap.size === 0 && layoutMap.size === 0) return withNodes
  return {
    ...withNodes,
    nodes: withNodes.nodes.map((n) => ({
      ...n,
      ...(sshMap.get(n.ip) ?? {}),
      ...(layoutMap.get(n.id) ?? layoutMap.get(n.ip)
        ? { position: layoutMap.get(n.id) ?? layoutMap.get(n.ip) }
        : {}),
    })),
  }
}

export function mergeClusterSpec(original: string, spec: ClusterSpec): string {
  let out = original
  const fresh = specToClusterConf(spec).split('\n').filter((l) => !l.startsWith('#'))
  for (const line of fresh) {
    if (!line.trim()) continue
    const m = line.match(/^([A-Z_0-9]+)=/)
    if (!m) continue
    const key = m[1]
    const re = new RegExp(`^${key}=.*$`, 'm')
    if (re.test(out)) out = out.replace(re, line)
    else out = `${out.replace(/\s*$/, '')}\n${line}\n`
  }
  return out
}

export function estimateInstallMinutes(spec: ClusterSpec): number {
  let m = 8
  if (spec.k8sDistro === 'kubespray') m += 25
  if (spec.k8sDistro === 'rke2' || spec.k8sDistro === 'talos' || spec.k8sDistro === 'microk8s')
    m += 15
  if (spec.kubevirtEnabled) m += 6
  if (spec.longhornEnabled) m += 5
  if (spec.gpuOperatorEnabled) m += 8
  m += spec.controlPlaneIps.length + spec.workerIps.length
  return m
}

export function installPlan(spec: ClusterSpec): string[] {
  const items: string[] = [spec.k8sDistro]
  if (spec.platformStackEnabled) {
    if (spec.cniPlugin === 'cilium') items.push('Cilium')
    if (spec.ciliumHubble) items.push('Hubble')
    if (spec.certManagerEnabled) items.push('cert-manager')
    if (spec.metallbEnabled) items.push('MetalLB')
    if (spec.metricsServerEnabled) items.push('metrics-server')
    if (spec.kubevirtEnabled) items.push('KubeVirt', 'CDI')
    if (spec.cnaoEnabled) items.push('CNAO')
    if (spec.sspEnabled) items.push('SSP')
    if (spec.longhornEnabled) items.push('Longhorn')
    if (spec.gpuOperatorEnabled) items.push('GPU Operator')
  }
  if (spec.k8sDistro === 'k3s' && spec.labSecondaryDisk) items.push('Lab storage', spec.labKubevirtStorageClass)
  if (spec.labMemoryTuneEnabled) items.push('Lab memory tune')
  return items
}
