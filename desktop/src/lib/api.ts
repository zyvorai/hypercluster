import { invoke } from '@tauri-apps/api/core'
import type { AppSettings, ClusterEntry, StatusJson, TestJson, WizardForm } from './types'

export async function listClusters(): Promise<ClusterEntry[]> {
  return invoke('list_clusters')
}

export async function getSettings(): Promise<AppSettings> {
  return invoke('get_settings')
}

export async function setSettings(settings: AppSettings): Promise<void> {
  return invoke('set_settings', { settings })
}

export async function importCluster(path: string): Promise<ClusterEntry> {
  return invoke('import_cluster_cmd', { path })
}

export async function pickClusterConf(): Promise<string | null> {
  return invoke('pick_cluster_conf')
}

export async function resolveBinary(): Promise<string> {
  return invoke('resolve_hypercluster_binary')
}

export async function createCluster(
  name: string,
  confContent: string,
  distro: string,
): Promise<ClusterEntry> {
  return invoke('create_cluster_cmd', { name, confContent, distro })
}

export async function pickSshKey(): Promise<string | null> {
  return invoke('pick_ssh_key')
}

export async function runCommand(req: {
  clusterName: string
  configPath: string
  command: string
  args?: string[]
  force?: boolean
  verbose?: boolean
  dryRun?: boolean
}): Promise<void> {
  return invoke('run_hypercluster_cmd', {
    req: {
      cluster_name: req.clusterName,
      config_path: req.configPath,
      command: req.command,
      args: req.args ?? [],
      force: req.force ?? false,
      verbose: req.verbose ?? false,
      dry_run: req.dryRun ?? false,
    },
  })
}

export async function cancelRun(clusterName: string): Promise<void> {
  return invoke('cancel_run_cmd', { clusterName })
}

export async function statusJson(configPath: string): Promise<StatusJson> {
  const raw = await invoke<string>('hc_status_json', { configPath })
  return JSON.parse(raw)
}

export async function testJson(configPath: string, full = false): Promise<TestJson> {
  const raw = await invoke<string>('hc_test_json', { configPath, full })
  return JSON.parse(raw)
}

export async function openDataDir(): Promise<void> {
  return invoke('open_data_dir')
}

export async function revealConfig(configPath: string): Promise<void> {
  return invoke('reveal_config', { configPath })
}

export function buildClusterConf(form: WizardForm): string {
  const lines: string[] = [
    '# hypercluster cluster configuration',
    '# Generated by Hypercluster Desktop',
    '',
    `CLUSTER_NAME="${form.clusterName}"`,
    '',
    `K8S_DISTRO="${form.k8sDistro}"`,
    `KUBESPRAY_VERSION="${form.kubesprayVersion}"`,
    `KUBESPRAY_DIR=".kubespray"`,
    `K3S_DATA_DIR="/data/k3s"`,
    `K3S_EXEC_ARGS="--flannel-backend=none --disable-network-policy --disable traefik --disable servicelb --disable-kube-proxy"`,
    `CILIUM_HUBBLE_ENABLED="true"`,
    `CILIUM_K8S_SERVICE_HOST="127.0.0.1"`,
    `PLATFORM_STACK_ENABLED="true"`,
    `CERT_MANAGER_ENABLED="true"`,
    `METALLB_ENABLED="${form.metallbEnabled ? 'true' : 'false'}"`,
    `METALLB_IP_POOL="${form.metallbIpPool}"`,
    `CDI_ENABLED="true"`,
    `KUBEVIRT_CSI_ENABLED="true"`,
    `KUBEVIRT_DISKS_PROVIDER="${form.kubevirtEnabled ? 'true' : 'false'}"`,
    `SNAPSHOT_CONTROLLER_ENABLED="true"`,
    `CNAO_ENABLED="true"`,
    `SSP_ENABLED="true"`,
    '',
    `KUBE_VERSION="${form.kubeVersion}"`,
    `CONTAINER_MANAGER="${form.containerManager}"`,
    `CNI_PLUGIN="${form.cniPlugin}"`,
    `KUBE_PODS_SUBNET="${form.kubePodsSubnet}"`,
    `KUBE_SERVICE_ADDRESSES="${form.kubeServiceAddresses}"`,
    '',
    `SSH_USER="${form.sshUser}"`,
    `SSH_KEY="${form.sshKey}"`,
    `SSH_PORT=${form.sshPort}`,
    `SSH_EXTRA_ARGS="-o StrictHostKeyChecking=no"`,
    '',
    `CONTROL_PLANE_IPS="${form.controlPlaneIps.join(' ')}"`,
    `WORKER_IPS="${form.workerIps.join(' ')}"`,
    '',
    `METRICS_SERVER_ENABLED="true"`,
    `KUBEVIRT_ENABLED="${form.kubevirtEnabled ? 'true' : 'false'}"`,
    `KUBEVIRT_VERSION="${form.kubevirtVersion}"`,
    `CDI_VERSION="${form.cdiVersion}"`,
    `KUBECONFIG_OUTPUT="$HOME/.kube/${form.clusterName}.yaml"`,
    `KUBECONFIG_MERGE_DEFAULT="false"`,
  ]
  return lines.join('\n') + '\n'
}

